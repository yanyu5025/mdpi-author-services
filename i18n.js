const LANG_STORAGE_KEY = "mdpi-as-lang";

function getLanguage() {
  try {
    const stored = localStorage.getItem(LANG_STORAGE_KEY);
    if (stored === "zh" || stored === "en") return stored;
  } catch {
    /* ignore */
  }
  return "en";
}

function t(key) {
  const lang = getLanguage();
  const parts = key.split(".");
  let value = MDPI_I18N[lang];
  for (const part of parts) {
    value = value?.[part];
  }
  if (value === undefined) {
    value = MDPI_I18N.en;
    for (const part of parts) {
      value = value?.[part];
    }
  }
  return value ?? key;
}

function applyTranslations(root = document) {
  const lang = getLanguage();
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(key);
  });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (key) el.innerHTML = t(key);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) el.placeholder = t(key);
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (key) el.setAttribute("aria-label", t(key));
  });
  root.querySelectorAll("[data-i18n-idle]").forEach((el) => {
    const key = el.getAttribute("data-i18n-idle");
    if (key) el.dataset.labelIdle = t(key);
  });
  root.querySelectorAll("[data-i18n-selected]").forEach((el) => {
    const key = el.getAttribute("data-i18n-selected");
    if (key) el.dataset.labelSelected = t(key);
  });

  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";

  root.querySelectorAll("[data-lang]").forEach((el) => {
    const optionLang = el.getAttribute("data-lang");
    const selected = optionLang === lang;
    el.classList.toggle("is-selected", selected);
    el.setAttribute("aria-selected", selected ? "true" : "false");
  });

  const enOption = root.querySelector('[data-lang="en"]');
  const zhOption = root.querySelector('[data-lang="zh"]');
  if (enOption) enOption.textContent = t("langEnglish");
  if (zhOption) zhOption.textContent = t("langChinese");
}

function setLanguage(lang) {
  if (lang !== "en" && lang !== "zh") return;
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch {
    /* ignore */
  }
  applyTranslations();
  window.dispatchEvent(new CustomEvent("mdpi-language-change", { detail: { lang } }));
}

function initLanguageSelector() {
  applyTranslations();
}

window.MdpiI18n = { t, getLanguage, setLanguage, applyTranslations, initLanguageSelector };

document.addEventListener("DOMContentLoaded", initLanguageSelector);
